// The keyboard's calculator without Unreal: reads lines from stdin, prints what the OLED would.
//   ./mcalc_cli            interactive
//   echo "hohmann(6678e3, 42164e3)" | ./mcalc_cli
//   ./mcalc_cli --markdown > Docs/FUNCTIONS.md      the function reference, from the registry
#include "CalcSession.h"

#include <cstdio>
#include <cstring>
#include <iostream>
#include <string>

namespace
{
std::string Cell(std::string S)
{
	std::string Out;
	for (char Ch : S)
	{
		Out += Ch == '|' ? std::string("\\|") : std::string(1, Ch);
	}
	return Out;
}

void PrintMarkdown()
{
	const mcalc::Registry& R = mcalc::Registry::Default();
	std::printf("# Function reference\n\nGenerated by `mcalc_cli --markdown` from the calculator's registry: %zu functions on %zu library pages. "
		"Square brackets mark optional arguments; units are SI and angles are radians unless stated. "
		"On the keyboard, F4 browses these pages and F1 shows the help for the name at the cursor.\n\n",
		R.All().size(), R.Categories().size());
	for (const std::string& Cat : R.Categories())
	{
		std::printf("- [%s](#%s) (%zu)\n", Cat.c_str(), Cat.c_str(), R.InCategory(Cat).size());
	}
	for (const std::string& Cat : R.Categories())
	{
		std::printf("\n## %s\n\n| Function | What it does | Returns | Source |\n|---|---|---|---|\n", Cat.c_str());
		for (const mcalc::FunctionInfo* F : R.InCategory(Cat))
		{
			std::printf("| `%s` | %s | %s | %s |\n", Cell(F->Signature()).c_str(), Cell(F->Summary).c_str(), Cell(F->Returns).c_str(), Cell(F->Source).c_str());
		}
	}
}
} // namespace

int main(int Argc, char** Argv)
{
	if (Argc > 1 && std::strcmp(Argv[1], "--markdown") == 0)
	{
		PrintMarkdown();
		return 0;
	}
	mcalc::Session S;
	std::string Line;
	while (std::printf("> "), std::fflush(stdout), std::getline(std::cin, Line))
	{
		const mcalc::Outcome O = S.Execute(Line);
		if (!O.Text.empty())
		{
			std::printf("%s%s\n", O.Ok ? (O.HasValue ? "= " : "") : "! ", O.Text.c_str());
		}
	}
	std::printf("\n");
	return 0;
}
